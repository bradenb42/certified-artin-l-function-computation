"""The decision rule for the functional equation, and the zeta anchor.

Runs the functional-equation test at a fixed pair of arguments against an
explicit tail bound, and applies the same rule to deliberately perturbed data
(a wrong root number, a wrong conductor, a wrong Euler factor, a wrong
Frobenius class) so that the test's power is measured rather than assumed.
Also computes the residue of the Dedekind zeta function of the subfield
generated by a root, from f alone, and compares it with the product of the
L-values obtained from the character data.
"""
from __future__ import annotations
import math, cmath
import mpmath

from .analytic import Kernel, dirichlet_coefficients, theta, zeta_subfield_coefficients
from .chartable import is_prime
from .ramified import factor_mod, decide_prime_for_factor, discriminant, factor_over_Z
from .archimedean import real_root_count
from .filtration import HardFailure

